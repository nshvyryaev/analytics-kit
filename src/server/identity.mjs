/**
 * Псевдоним игрока: HMAC, а не хеш.
 *
 * Идентификаторы ВКонтакте и Одноклассников последовательны и лежат в
 * диапазоне порядка 10⁹. Голый SHA-256 от такого идентификатора взламывается
 * перебором всего пространства за минуты на обычной видеокарте, и утёкший дамп
 * разворачивается обратно в список конкретных людей целиком. Ключ убирает саму
 * возможность перебора: считать не от чего.
 *
 * Пространства имён разделены префиксом. Без него «анонимный vk:1» и «игрок
 * vk:1» дали бы один псевдоним, и локальный гость склеился бы со случайным
 * игроком ВКонтакте.
 */
import { createHmac } from 'node:crypto';

/**
 * 22 символа base64url — это 132 бита (16.5 байта). Этого с запасом хватает
 * для защиты от коллизий на наших объёмах.
 */

export function subject(namespaced, key) {
  // Пустой ключ — не «считать без ключа», а нечем считать. Тихо посчитанный
  // пустым ключом псевдоним обратим перебором и притворяется защищённым.
  if (typeof key !== 'string' || key.length === 0) {
    throw new Error('нужен непустой ключ псевдонимов');
  }
  return createHmac('sha256', key)
    .update(namespaced)
    .digest('base64')
    .slice(0, 22)
    .replace(/\+/g, '-')
    .replace(/\//g, '_');
}

export const playerSubject = (platform, playerId, key) =>
  subject(`p:${platform.length}:${platform}:${playerId}`, key);

// anonSubject не кодирует длину анонима, потому что это одно поле и склеивать
// нечего — нет соседних полей, которые могли бы создать коллизию при совпадении
// границ как в playerSubject('vk', '1:2') vs playerSubject('vk:1', '2').
export const anonSubject = (anonId, key) => subject(`a:${anonId}`, key);
